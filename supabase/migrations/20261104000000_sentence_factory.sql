-- =====================================================================
--  Sentence Factory 360° — database schema
--  Run with:  supabase db push   (or paste into Supabase SQL Editor)
--
--  Security model
--  --------------
--  * Every table has Row Level Security ENABLED and NO policies, and all
--    privileges are revoked from the `anon` and `authenticated` roles.
--    The browser therefore cannot read or write any table directly.
--  * All reads/writes go through Supabase Edge Functions, which use the
--    service-role key on the server only, and which check the classroom
--    access code (students) or a signed teacher session (teachers).
--  * Photos and recordings live in a PRIVATE storage bucket and are only
--    ever handed out as short-lived signed URLs.
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- Settings (single row)
-- ---------------------------------------------------------------------
create table if not exists public.app_settings (
  id               int primary key default 1 check (id = 1),
  classroom_name   text not null default 'Our Sentence Factory',
  teacher_pin_hash text,                       -- PBKDF2 hash; null = use INITIAL_TEACHER_PIN secret
  photo_required   boolean not null default true,
  word_of_day      jsonb,                      -- {"word": "...", "meaning": "...", "date": "YYYY-MM-DD"}
  challenge        jsonb,                      -- {"title": "...", "required_word": "..."|null, "min_words": n|null}
  updated_at       timestamptz not null default now()
);

insert into public.app_settings (id) values (1) on conflict (id) do nothing;

-- ---------------------------------------------------------------------
-- Classes and their access codes
-- ---------------------------------------------------------------------
create table if not exists public.classes (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  access_code text not null,
  created_at  timestamptz not null default now(),
  constraint classes_name_len check (char_length(name) between 1 and 40),
  constraint classes_code_len check (char_length(access_code) between 4 and 20)
);
create unique index if not exists classes_name_unique on public.classes (lower(name));

-- ---------------------------------------------------------------------
-- Word bank
-- ---------------------------------------------------------------------
create table if not exists public.word_bank (
  id          uuid primary key default gen_random_uuid(),
  category    text not null check (category in ('who', 'what', 'where', 'when')),
  text        text not null,
  is_plural   boolean not null default false,  -- WHO only: "My friends" = true (uses "are")
  sort_order  int not null default 0,
  created_at  timestamptz not null default now(),
  constraint word_bank_text_len check (char_length(text) between 1 and 60)
);
create unique index if not exists word_bank_unique on public.word_bank (category, lower(text));

-- ---------------------------------------------------------------------
-- Submissions
-- ---------------------------------------------------------------------
create table if not exists public.submissions (
  id                 uuid primary key,          -- generated by the tablet (idempotency key: stops double-tap duplicates)
  pupil_name         text not null,
  class_name         text not null,
  class_id           uuid references public.classes(id) on delete set null,
  sentence           text not null,
  who                text not null,
  what_happens       text not null,
  where_text         text not null,
  when_text          text not null,
  photo_path         text,
  audio_path         text not null,
  audio_mime         text,
  audio_duration_ms  int,
  status             text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  share_token        text unique,               -- long-lived random token used in the QR code (set on approval)
  challenge_done     boolean not null default false,
  used_word_of_day   boolean not null default false,
  reviewed_at        timestamptz,
  created_at         timestamptz not null default now(),
  constraint submissions_name_len check (char_length(pupil_name) between 1 and 40)
);
create index if not exists submissions_status_idx on public.submissions (status, created_at desc);
create index if not exists submissions_class_idx  on public.submissions (class_name);

-- ---------------------------------------------------------------------
-- Login attempts (brute-force protection for the teacher PIN)
-- ---------------------------------------------------------------------
create table if not exists public.login_attempts (
  id         bigserial primary key,
  ip         text not null,
  success    boolean not null,
  created_at timestamptz not null default now()
);
create index if not exists login_attempts_ip_idx on public.login_attempts (ip, created_at desc);

-- ---------------------------------------------------------------------
-- Lock everything down: RLS on, no policies, no grants to browser roles
-- ---------------------------------------------------------------------
alter table public.app_settings   enable row level security;
alter table public.classes        enable row level security;
alter table public.word_bank      enable row level security;
alter table public.submissions    enable row level security;
alter table public.login_attempts enable row level security;

revoke all on public.app_settings, public.classes, public.word_bank,
              public.submissions, public.login_attempts
  from anon, authenticated;
revoke all on sequence public.login_attempts_id_seq from anon, authenticated;

