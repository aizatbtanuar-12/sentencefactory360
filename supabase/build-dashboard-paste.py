#!/usr/bin/env python3
"""Regenerate supabase/dashboard-paste/*.ts (single-file Edge Functions for the
Supabase dashboard editor) from supabase/functions/. Run: python3 supabase/build-dashboard-paste.py"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
fn = os.path.join(here, 'functions')
out_dir = os.path.join(here, 'dashboard-paste')
strip = lambda s: re.sub(r'^export (?=(async |function|const|class|interface|type|let))', '', s, flags=re.M)
shared = {n: strip(open(os.path.join(fn, '_shared', n + '.ts')).read()) for n in ('util', 'sentence')}
for name in ('student', 'teacher', 'listen'):
    src = open(os.path.join(fn, name, 'index.ts')).read()
    uses = [n for n in ('util', 'sentence') if f"'../_shared/{n}.ts'" in src]
    src = re.sub(r"import\s*(type\s*)?\{[^}]*\}\s*from\s*'\.\./_shared/[^']+';\n", '', src, flags=re.S)
    head = (f'// =====================================================================\n'
            f'//  Sentence Factory 360° — Edge Function "{name}" (single-file version)\n'
            f'//  Paste into Supabase Dashboard → Edge Functions → Deploy a new function\n'
            f'//  → Via Editor. Name the function exactly:  {name}\n'
            f'//  Then turn OFF "Enforce JWT verification" for it.\n'
            f'//  GENERATED by supabase/build-dashboard-paste.py — do not edit by hand.\n'
            f'// =====================================================================\n')
    body = head + ''.join(f'\n// ---------- shared: {n}.ts ----------\n' + shared[n] for n in uses) + '\n// ---------- function ----------\n' + src
    open(os.path.join(out_dir, name + '.ts'), 'w').write(body)
    print('wrote', name + '.ts', f'({len(body.splitlines())} lines, uses {uses})')
